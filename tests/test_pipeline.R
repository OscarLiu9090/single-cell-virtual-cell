})
testthat::test_that("add-one is lost at pcNet scaling but CPM can introduce compositional effects", {
  set.seed(7); x <- matrix(rpois(30 * 70, 3), 30, dimnames = list(paste0("g", 1:30), paste0("c", 1:70)))
  y <- x; y[1, ] <- y[1, ] + 1
  a <- scTenifoldNet::pcNet(x, nComp = 3, q = 0, nCores = 1)
  b <- scTenifoldNet::pcNet(y, nComp = 3, q = 0, nCores = 1)
  testthat::expect_equal(as.matrix(a), as.matrix(b), tolerance = 1e-7)
  nx <- scTenifoldNet::cpmNormalization(x); ny <- scTenifoldNet::cpmNormalization(y)
  testthat::expect_true(max(abs(nx[-1, ] - ny[-1, ])) > 0)
})
testthat::test_that("official KO statistics match the shared-network adapter and repeat", {
  set.seed(42)
  x <- matrix(rpois(30 * 80, 4), 30, dimnames = list(paste0("g", 1:30), paste0("c", 1:80)))
  go <- function() scTenifoldKnk::scTenifoldKnk(x, gKO = "g1", qc = FALSE, nc_nNet = 3, nc_nCells = 50, td_K = 3, td_maxIter = 30, dr_direction = FALSE, nCores = 1, seed = 11)
  a <- go(); b <- go()
  testthat::expect_equal(a$tensorNetworks$WT, b$tensorNetworks$WT)
  testthat::expect_equal(a$diffRegulation, b$diffRegulation, tolerance = 1e-7)
  wt <- as.matrix(a$tensorNetworks$WT)
  cfg <- list(network = list(ma_dim = 2, n_cores = 1))
  d <- compare_network(wt, perturb_edges(wt, "g1", 0), "g1", cfg, 11)
  testthat::expect_equal(d[, names(a$diffRegulation)], a$diffRegulation, tolerance = 1e-7)
  testthat::expect_false("direction" %in% names(d))
})

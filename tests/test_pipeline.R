testthat::test_that("RDS and RData adapters preserve counts and reject ambiguous objects", {
  set.seed(19)
  m <- Matrix::Matrix(matrix(rpois(60, 3), 10, dimnames = list(paste0("g", 1:10), paste0("c", 1:6))), sparse = TRUE)
  myObject <- Seurat::CreateSeuratObject(m, min.cells = 0, min.features = 0)
  folder <- file.path(root, ".test-output", "r_objects"); dir.create(folder, recursive = TRUE, showWarnings = FALSE)
  saveRDS(myObject, file.path(folder, "object.rds")); save(myObject, file = file.path(folder, "object.RData"))
  cfg <- list(input = list(type = "seurat_rds", path = "object.rds"))
  a <- load_input(cfg, folder, folder, root, runtime)
  cfg$input <- list(type = "seurat_rdata", path = "object.RData", object_name = "myObject")
  b <- load_input(cfg, folder, folder, root, runtime)
  testthat::expect_equal(a$counts, b$counts)
  another <- myObject; save(myObject, another, file = file.path(folder, "ambiguous.RData"))
  cfg$input <- list(type = "seurat_rdata", path = "ambiguous.RData")
  testthat::expect_error(load_input(cfg, folder, folder, root, runtime), "AMBIGUOUS_RDATA")
})

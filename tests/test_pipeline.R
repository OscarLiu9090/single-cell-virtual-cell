testthat::test_that("KO/OE change outgoing row only, and sham is exactly neutral", {
  wt <- matrix(1:25 / 25, 5, dimnames = list(LETTERS[1:5], LETTERS[1:5])); diag(wt) <- 0
  ko <- perturb_edges(wt, "B", 0); oe <- perturb_edges(wt, "B", 5)
  testthat::expect_true(all(ko["B", ] == 0))
  testthat::expect_equal(oe["B", ], wt["B", ] * 5)
  testthat::expect_identical(ko[-2, ], wt[-2, ])
  testthat::expect_identical(oe[-2, ], wt[-2, ])
  testthat::expect_identical(perturb_edges(wt, "B", 1), wt)
  dr <- compare_network(wt, wt, "B", list(), 1)
  testthat::expect_true(all(dr$p.adj == 1 & dr$distance == 0))
  testthat::expect_true(all(is.na(dr$FC)))
  dr$is_target <- dr$gene == "B"; dr$rank <- NA_real_
  out <- file.path(root, ".test-output", "null_network.pdf")
  dir.create(dirname(out), recursive = TRUE, showWarnings = FALSE)
  testthat::expect_silent(plot_network_result(dr, out, "A"))

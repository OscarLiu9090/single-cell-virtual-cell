testthat::test_that("counts preserve orientation and reject transformed/duplicate data", {
  m <- matrix(1:12, 3, dimnames = list(c("A", "B", "B"), paste0("c", 1:4)))
  testthat::expect_s4_class(validate_counts(m), "dgCMatrix")
  collapsed <- collapse_symbols(validate_counts(m), rownames(m))
  testthat::expect_equal(as.numeric(collapsed$counts["B", ]), as.numeric(m[2, ] + m[3, ]))
  testthat::expect_equal(sum(collapsed$counts), sum(m))
  testthat::expect_error(validate_counts(log1p(m)), "RAW_COUNTS_REQUIRED")
  colnames(m)[2] <- colnames(m)[1]
  testthat::expect_error(validate_counts(m), "DUPLICATE_CELL")
})
